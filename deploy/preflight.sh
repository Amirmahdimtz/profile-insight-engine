#!/bin/sh
set -eu

fail() {
    echo "deployment preflight: $*" >&2
    exit 1
}

[ -f .env ] || fail "missing .env; copy .env.example and generate both database passwords"
[ -s deploy/tls/fullchain.pem ] || fail "missing deploy/tls/fullchain.pem"
[ -s deploy/tls/privkey.pem ] || fail "missing deploy/tls/privkey.pem"
[ -s deploy/secrets/.htpasswd ] || fail "missing deploy/secrets/.htpasswd"

read_env() {
    sed -n "s/^$1=//p" .env
}

POSTGRES_DB="$(read_env POSTGRES_DB)"
POSTGRES_USER="$(read_env POSTGRES_USER)"
POSTGRES_PASSWORD="$(read_env POSTGRES_PASSWORD)"
APP_DB_USER="$(read_env APP_DB_USER)"
APP_DB_PASSWORD="$(read_env APP_DB_PASSWORD)"

printf '%s\n' "$POSTGRES_DB" | grep -Eq '^[A-Za-z0-9_]+$' || fail "POSTGRES_DB must use letters, digits, and underscores"
printf '%s\n' "$POSTGRES_USER" | grep -Eq '^[A-Za-z0-9_]+$' || fail "POSTGRES_USER must use letters, digits, and underscores"
printf '%s\n' "$APP_DB_USER" | grep -Eq '^[A-Za-z0-9_]+$' || fail "APP_DB_USER must use letters, digits, and underscores"
[ "$POSTGRES_USER" != "$APP_DB_USER" ] || fail "APP_DB_USER must differ from the PostgreSQL bootstrap/admin role"
[ "$POSTGRES_PASSWORD" != "$APP_DB_PASSWORD" ] || fail "bootstrap/admin and application DB passwords must differ"
printf '%s\n' "$POSTGRES_PASSWORD" | grep -Eq '^[0-9a-f]{64}$' || fail "POSTGRES_PASSWORD must be 64 lowercase hex characters generated by openssl rand -hex 32"
printf '%s\n' "$APP_DB_PASSWORD" | grep -Eq '^[0-9a-f]{64}$' || fail "APP_DB_PASSWORD must be 64 lowercase hex characters generated by openssl rand -hex 32"

hostnames="$(awk '/^[[:space:]]*server_name[[:space:]]/ { gsub(/;/, "", $2); print $2 }' deploy/nginx/default.conf | sort -u)"
[ "$(printf '%s\n' "$hostnames" | wc -l | tr -d ' ')" = "1" ] || fail "Nginx server_name directives must use one hostname"
hostname="$hostnames"
printf '%s\n' "$hostname" | grep -Eq '^[A-Za-z0-9.-]+$' || fail "replace the example hostname with a valid DNS name"
[ "$hostname" != "example.com" ] || fail "replace example.com in deploy/nginx/default.conf"
grep -Fq "return 308 https://${hostname}\$request_uri;" deploy/nginx/default.conf || fail "HTTP redirect hostname must match server_name"

openssl x509 -in deploy/tls/fullchain.pem -noout -checkend 0 >/dev/null 2>&1 || fail "TLS certificate is expired or unreadable"
openssl x509 -in deploy/tls/fullchain.pem -noout -checkhost "$hostname" >/dev/null 2>&1 || fail "TLS certificate does not cover $hostname"
openssl pkey -in deploy/tls/privkey.pem -noout >/dev/null 2>&1 || fail "TLS private key is unreadable or encrypted"
cert_key="$(openssl x509 -in deploy/tls/fullchain.pem -pubkey -noout | openssl pkey -pubin -outform DER | sha256sum | awk '{print $1}')"
private_key="$(openssl pkey -in deploy/tls/privkey.pem -pubout -outform DER | sha256sum | awk '{print $1}')"
[ "$cert_key" = "$private_key" ] || fail "TLS certificate and private key do not match"
grep -Eq '^[^:]+:\$2[aby]\$' deploy/secrets/.htpasswd || fail "htpasswd file must contain a bcrypt entry created with htpasswd -B"

for secret_file in .env deploy/secrets/.htpasswd deploy/tls/privkey.pem; do
    mode="$(stat -c '%a' "$secret_file" 2>/dev/null)" || fail "cannot inspect permissions for $secret_file"
    [ $((0$mode & 077)) -eq 0 ] || fail "$secret_file must not be readable by group/other; chmod 600"
done

docker compose config --quiet || fail "docker compose config failed; inspect the non-secret validation errors"
echo "deployment preflight passed for hostname $hostname"
